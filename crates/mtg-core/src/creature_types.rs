/// Whether a subtype name is a creature type.
pub fn is_creature_type(name: &str) -> bool {
    CREATURE_TYPES.binary_search(&name).is_ok()
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn list_is_sorted_so_binary_search_works() {
        assert!(CREATURE_TYPES.windows(2).all(|w| w[0] < w[1]));
    }

    #[test]
    fn creature_types_are_told_apart_from_other_subtypes() {
        for t in [
            "Goblin",
            "Sliver",
            "Assembly-Worker",
            "C'tan",
            "Dinosaur",
            "Scion",
        ] {
            assert!(is_creature_type(t), "{t}");
        }
        for t in [
            "Forest",
            "Equipment",
            "Aura",
            "Treasure",
            "Jace",
            "Saga",
            "Vehicle",
        ] {
            assert!(!is_creature_type(t), "{t}");
        }
    }
}
